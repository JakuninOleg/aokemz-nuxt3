const activeId = ref(LEGAL_NAV[0]?.id ?? "policy-general");

const syncFromHash = () => {
  if (!import.meta.client) return;
  const id = window.location.hash.replace(/^#/, "");
  if (id && LEGAL_NAV.some((item) => item.id === id)) {
    activeId.value = id;
  }
};

const onScroll = () => {
  if (!import.meta.client) return;

  const activateLine = Math.min(160, window.innerHeight * 0.32);
  let current = LEGAL_NAV[0]?.id ?? "policy-general";

  for (const item of LEGAL_NAV) {
    const el = document.getElementById(item.id);
    if (!el) continue;
    if (el.getBoundingClientRect().top <= activateLine) {
      current = item.id;
    }
  }

  activeId.value = current;
};

const onNavClick = (id: string) => {
  activeId.value = id;
};

onMounted(() => {
  syncFromHash();
  onScroll();
  window.addEventListener("scroll", onScroll, { passive: true });
  window.addEventListener("hashchange", syncFromHash);
});

onBeforeUnmount(() => {
  if (!import.meta.client) return;
  window.removeEventListener("scroll", onScroll);
  window.removeEventListener("hashchange", syncFromHash);
});
</script>

